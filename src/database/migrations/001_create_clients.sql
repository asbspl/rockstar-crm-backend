CREATE TABLE IF NOT EXISTS public.clients (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  client_name TEXT NOT NULL,
  phone TEXT,
  email TEXT,
  address_line1 TEXT,
  address_line2 TEXT,
  country TEXT,
  state TEXT,
  city TEXT,
  pin_code TEXT,
  location TEXT,
  addition_date DATE NOT NULL DEFAULT CURRENT_DATE,
  gstin TEXT,
  contact_person TEXT,
  status TEXT NOT NULL DEFAULT 'active',
  credit_days INTEGER NOT NULL DEFAULT 0,
  assigned_employee TEXT,
  delivery_challan_provided BOOLEAN NOT NULL DEFAULT FALSE,
  gst_document_path TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT clients_pkey PRIMARY KEY (id),
  CONSTRAINT clients_client_name_nonempty CHECK (btrim(client_name) <> ''),
  CONSTRAINT clients_email_format CHECK (
    email IS NULL OR email ~* '^[^[:space:]@]+@[^[:space:]@]+[.][^[:space:]@]+$'
  ),
  CONSTRAINT clients_status_nonempty CHECK (btrim(status) <> ''),
  CONSTRAINT clients_credit_days_nonnegative CHECK (credit_days >= 0)
);